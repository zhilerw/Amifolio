using Amifolio.Desktop;

var root = Path.Combine(Path.GetTempPath(), "amifolio-undo-logic");
var fileA = Path.Combine(root, "a", "AGENTS.md");
var fileB = Path.Combine(root, "b", "AGENTS.md");
var undo = new AgentsUndoState();
undo.Record(fileA, Path.Combine(root, "a.bak"), "COMMON");
Check(undo.CanRestore(fileA, "COMMON", exists: true), "same saved target should restore");
Check(!undo.CanRestore(fileB, "COMMON", exists: true), "matching bytes in another file must never authorize restoration");
Check(!undo.CanRestore(fileA, "EXTERNAL_CHANGE", exists: true), "external changes must invalidate restoration");
Check(!undo.CanRestore(fileA, "COMMON", exists: false), "a deleted file must not restore even when its hash matches the saved empty content");
undo.FileLoaded(fileB, "COMMON", exists: true);
Check(!undo.HasBackup, "loading another target must clear the old backup");
undo.Record(fileA, Path.Combine(root, "a.bak"), "COMMON");
undo.FileLoaded(fileA, "COMMON", exists: true);
Check(undo.HasBackup, "rereading the same target should retain its backup");
undo.FileLoaded(fileA, "EXTERNAL_CHANGE", exists: true);
Check(!undo.HasBackup, "rereading changed content must retire stale undo");
undo.Record(fileA, Path.Combine(root, "a.bak"), "COMMON");
undo.FileLoaded(fileA, "COMMON", exists: false);
Check(!undo.HasBackup, "rereading a deleted empty file must retire stale undo");
undo.Record(fileA, null, "NEW_FILE");
Check(!undo.HasBackup, "new file without backup must not offer undo");
undo.Record(fileA, Path.Combine(root, "a.bak"), "COMMON");
undo.Clear();
Check(!undo.CanRestore(fileA, "COMMON", exists: true), "cleared state cannot restore");
Console.WriteLine("PASS 10 undo target/hash/lifecycle assertions");
var edit = new DocumentEditState();
edit.Load("第一行\n第二行\n", true);
Check(!edit.HasChanges("第一行\r第二行\r"), "loading into a CR-normalizing native editor must not mark LF content dirty");
Check(!edit.IsEditing, "documents must open read-only");
Check(edit.Begin(), "editable document can enter edit mode");
Check(!edit.HasChanges("第一行\r\n第二行\r\n"), "equivalent CRLF text must remain clean even in edit mode");
Check(edit.HasChanges("第一行\r第二行已改\r"), "real text changes must remain dirty");
Check(edit.TextForSave("第一行\r第二行已改\r") == "第一行\n第二行已改\n", "saving native CR text must restore LF instead of writing CR-only Markdown");
Check(edit.Cancel() == "第一行\n第二行\n" && !edit.IsEditing, "cancel must restore original content and exit editing");
Check(!edit.HasChanges("第一行\r第二行已改\r"), "read-only display refreshes cannot create unsaved edits");
edit.Load("a\r\nb\r\n", true);
edit.Begin();
Check(edit.TextForSave("a\rb changed\r") == "a\r\nb changed\r\n", "save must retain Windows line endings");
Check(edit.HasChanges("a \rb\r"), "significant spaces must not be trimmed in dirty detection");
Check(edit.TextForSave("a\rb\r") == "a\r\nb\r\n", "unchanged save must preserve original text exactly");
edit.Load("a\r\nb\nc\r", true);
edit.Begin();
Check(edit.TextForSave("a\rb changed\rc\r") == "a\r\nb changed\r\nc\r", "unchanged prefix/suffix line endings must survive a local edit");
edit.Load("# readonly\n", false);
Check(!edit.Begin() && !edit.IsEditing, "generated/read-only documents must reject edit mode");
Console.WriteLine("PASS 13 document edit/normalization/cancel assertions");
await BrowserCases.RunAsync();
return 0;
static void Check(bool condition, string message) { if (!condition) throw new Exception(message); }
